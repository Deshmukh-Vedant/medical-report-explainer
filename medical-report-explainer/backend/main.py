"""
main.py
--------
FastAPI application entrypoint for the AI Medical Report Explainer.

Run with:
    uvicorn main:app --reload --port 8000
"""

import logging
import os

from fastapi import FastAPI, Request, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, FileResponse
from fastapi.staticfiles import StaticFiles
from slowapi import Limiter, _rate_limit_exceeded_handler
from slowapi.util import get_remote_address
from slowapi.errors import RateLimitExceeded

from models.database import init_db
from routes import auth, upload, analysis, history, profile, predict

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("main")

# --- Rate limiter (protects auth & upload endpoints from abuse) ---
limiter = Limiter(key_func=get_remote_address, default_limits=["100/hour"])

app = FastAPI(
    title="AI Medical Report Explainer API",
    description=(
        "Upload medical reports and get simple-language AI explanations. "
        "This API is for educational purposes only and does not provide "
        "medical advice."
    ),
    version="1.0.0",
)

app.state.limiter = limiter
app.add_exception_handler(RateLimitExceeded, _rate_limit_exceeded_handler)

# --- CORS: allow local development and Netlify frontend ---
cors_origins_env = os.getenv("CORS_ORIGINS", "")
allowed_origins = [
    "http://127.0.0.1:5500",
    "http://localhost:5500",
    "http://127.0.0.1:5501",
    "http://localhost:5501",
    "http://localhost:5502",
    "http://127.0.0.1:5502",
    "http://localhost:8080",
    "http://127.0.0.1:8080",
    "http://127.0.0.1:8000",
    "http://localhost:8000",
    "http://localhost:3000",
]
if cors_origins_env:
    for origin in cors_origins_env.split(","):
        origin_clean = origin.strip()
        if origin_clean and origin_clean not in allowed_origins:
            allowed_origins.append(origin_clean)

app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    allow_origin_regex=r"^https:\/\/.*\.netlify\.app$",
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.on_event("startup")
def on_startup():
    """Creates database tables if they don't already exist."""
    init_db()
    logger.info("Database initialized. AI Medical Report Explainer API is ready.")


@app.get("/health", tags=["Health"])
@app.get("/api/health", tags=["Health"])
def health_check():
    return {
        "status": "ok",
        "service": "AI Medical Report Explainer API",
        "disclaimer": (
            "This explanation is generated by AI and is for educational "
            "purposes only. It is NOT medical advice. Please consult a "
            "qualified doctor."
        ),
    }


@app.get("/dashboard", tags=["Health"])
def dashboard_health():
    """Lightweight endpoint the frontend dashboard can ping to verify connectivity."""
    return {"status": "ok"}


# --- Frontend Static Files & Pages (for all-in-one local & Render deployment) ---
FRONTEND_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "frontend"))
if os.path.isdir(FRONTEND_DIR):
    css_dir = os.path.join(FRONTEND_DIR, "css")
    js_dir = os.path.join(FRONTEND_DIR, "js")
    if os.path.isdir(css_dir):
        app.mount("/css", StaticFiles(directory=css_dir), name="css")
    if os.path.isdir(js_dir):
        app.mount("/js", StaticFiles(directory=js_dir), name="js")

    @app.get("/", tags=["Frontend"])
    def root(request: Request):
        accept = request.headers.get("accept", "")
        index_path = os.path.join(FRONTEND_DIR, "index.html")
        if ("text/html" in accept or "*/*" in accept) and os.path.exists(index_path):
            return FileResponse(index_path)
        return health_check()

    @app.get("/{page}.html", tags=["Frontend"])
    def serve_html(page: str):
        page_path = os.path.join(FRONTEND_DIR, f"{page}.html")
        if os.path.exists(page_path):
            return FileResponse(page_path)
        raise HTTPException(status_code=404, detail=f"Page {page}.html not found")
else:
    @app.get("/", tags=["Health"])
    def root():
        return health_check()


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    logger.exception("Unhandled error on %s", request.url)
    return JSONResponse(
        status_code=500,
        content={"detail": "An unexpected server error occurred. Please try again."},
    )


# --- Routers ---
app.include_router(auth.router)
app.include_router(upload.router)
app.include_router(analysis.router)
app.include_router(history.router)
app.include_router(profile.router)
app.include_router(predict.router)


if __name__ == "__main__":
    import uvicorn
    port = int(os.getenv("PORT", "8000"))
    uvicorn.run("main:app", host="0.0.0.0", port=port, reload=False)

