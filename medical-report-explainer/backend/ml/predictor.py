"""
ml/predictor.py
----------------
Loads the trained lab risk classifier and exposes a predict() function.

The model artifact is a dict saved by train.py containing:
  pipeline      — sklearn Pipeline (imputer + RandomForest)
  feature_names — list of 10 feature name strings
  label_names   — ["Low", "Moderate", "High"]
  version       — model version string

predict() accepts extracted lab params (with None for missing values),
builds the feature vector, runs inference, and returns a PredictionResult.
"""

import logging
import os
from dataclasses import dataclass, field
from typing import Optional

import numpy as np

logger = logging.getLogger("ml.predictor")

_MODEL_PATH = os.getenv(
    "ML_MODEL_PATH",
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "models", "lab_risk_classifier.pkl")
)

_model_artifact = None  # loaded lazily


@dataclass
class PredictionResult:
    risk_label: str
    confidence: float
    extracted_params: dict
    missing_params: list = field(default_factory=list)
    model_version: str = "unknown"
    disclaimer: str = (
        "This prediction is generated by an ML model trained on synthetic data. "
        "It has NOT been clinically validated and must NOT be used for medical decisions. "
        "Always consult a qualified healthcare professional."
    )


def _load_model():
    global _model_artifact
    if _model_artifact is not None:
        return _model_artifact

    try:
        import joblib
        _model_artifact = joblib.load(_MODEL_PATH)
        logger.info(
            "ML model loaded: version=%s, features=%s",
            _model_artifact.get("version"),
            _model_artifact.get("feature_names"),
        )
        return _model_artifact
    except FileNotFoundError:
        logger.error(
            "ML model not found at %s. Run `python -m ml.train` to generate it.",
            _MODEL_PATH,
        )
        raise
    except Exception as exc:
        logger.exception("Failed to load ML model: %s", exc)
        raise


def predict(params: dict) -> PredictionResult:
    """
    Runs risk prediction on a dict of lab parameters.

    Args:
        params: dict mapping feature name → float | None.
                None values are passed as NaN; the pipeline imputer handles them.

    Returns:
        PredictionResult with risk_label, confidence (0–1), and metadata.

    Raises:
        RuntimeError: if the model cannot be loaded.
    """
    try:
        artifact = _load_model()
    except Exception as exc:
        raise RuntimeError(f"ML model unavailable: {exc}") from exc

    feature_names: list = artifact["feature_names"]
    label_names: list = artifact["label_names"]
    pipeline = artifact["pipeline"]
    version: str = artifact.get("version", "unknown")

    # Build feature vector
    feature_vector = []
    missing = []
    extracted = {}
    for name in feature_names:
        val = params.get(name)
        if val is None:
            feature_vector.append(np.nan)
            missing.append(name)
        else:
            feature_vector.append(float(val))
            extracted[name] = float(val)

    X = np.array(feature_vector, dtype=float).reshape(1, -1)

    proba = pipeline.predict_proba(X)[0]
    predicted_idx = int(np.argmax(proba))
    confidence = float(proba[predicted_idx])
    risk_label = label_names[predicted_idx]

    logger.info(
        "ML prediction: %s (confidence=%.2f, missing=%s)",
        risk_label, confidence, missing,
    )

    return PredictionResult(
        risk_label=risk_label,
        confidence=confidence,
        extracted_params=extracted,
        missing_params=missing,
        model_version=version,
    )


def model_available() -> bool:
    """Returns True if the model file exists and can be loaded."""
    return os.path.exists(_MODEL_PATH)
